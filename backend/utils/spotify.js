// Helper to parse Flask JioSaavn results (used for both local and public Flask servers)
const parseFlaskResults = (results) => {
  const uniqueItemsMap = new Map();
  results.forEach(item => {
    const id = item.id || item.songid || item.e_songid;
    if (id && !uniqueItemsMap.has(id)) {
      uniqueItemsMap.set(id, item);
    }
  });

  const uniqueResults = Array.from(uniqueItemsMap.values());
  const tracks = uniqueResults.map(item => {
    // singers -> "Marshmello, Pritam Chakraborty..."
    // url -> stream link
    // image_url -> 500x500 cover art
    const artistList = item.singers ? item.singers.split(',').map(s => s.trim()) : ['JioSaavn Artist'];
    
    // Force high resolution image replacing
    const rawImage = item.image || item.image_url;
    const artwork = rawImage 
      ? rawImage.replace('150x150', '500x500') 
      : 'https://images.unsplash.com/photo-1514525253161-7a46d19cd819?w=300&q=80';

    // Deterministic seeded acoustic profiles from songid hash
    let hash = 0;
    const str = item.id || item.songid || item.e_songid || '12345';
    for (let i = 0; i < str.length; i++) {
      hash = str.charCodeAt(i) + ((hash << 5) - hash);
    }
    const seed = Math.abs(hash);
    const energy = ((seed % 7) + 3) / 10;
    const danceability = ((seed % 5) + 4) / 10;
    const valence = ((seed % 9) + 1) / 10;
    const acousticness = ((seed % 6) + 1) / 10;
    const tempo = Math.round((seed % 60) + 70);

    const language = item.language ? item.language.charAt(0).toUpperCase() + item.language.slice(1) : 'English';

    return {
      spotifyId: `saavn_${item.id || item.songid || item.e_songid || seed}`,
      name: item.title || item.song || 'JioSaavn Song',
      artists: artistList,
      albumName: item.album || 'Single',
      artworkUrl: artwork,
      durationMs: (item.duration ? parseInt(item.duration) * 1000 : 0) || 180000,
      previewUrl: item.url || item.media_url || '',
      energy,
      danceability,
      tempo,
      acousticness,
      valence,
      popularity: 92,
      language,
      genre: 'Bollywood'
    };
  });

  const playableTracks = tracks.filter(t => t.previewUrl !== '');
  return {
    tracks: playableTracks.length > 0 ? playableTracks : tracks,
    artists: [...new Set(tracks.flatMap(t => t.artists))].map(name => ({ name, images: [{ url: 'https://images.unsplash.com/photo-1508700115892-45ecd05ae2ad?w=100&q=80' }] })),
    albums: [...new Set(tracks.map(t => t.albumName))].map(name => ({ name, images: [{ url: 'https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=100&q=80' }] }))
  };
};

