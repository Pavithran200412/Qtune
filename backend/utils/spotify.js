export const getSpotifyTokensFromCode = async (code) => {
  const clientId = process.env.SPOTIFY_CLIENT_ID;
  const clientSecret = process.env.SPOTIFY_CLIENT_SECRET;
  const redirectUri = process.env.SPOTIFY_REDIRECT_URI;

  if (!clientId || !clientSecret || clientId.startsWith('spotify_dummy')) {
    // If dummy, return mock tokens
    return {
      accessToken: 'mock_access_token_' + Date.now(),
      refreshToken: 'mock_refresh_token_xyz',
      expiresIn: 3600,
      spotifyId: 'mock_user_spotify_id'
    };
  }

  try {
    const params = new URLSearchParams();
    params.append('grant_type', 'authorization_code');
    params.append('code', code);
    params.append('redirect_uri', redirectUri);

    const authHeader = Buffer.from(`${clientId}:${clientSecret}`).toString('base64');

    const res = await fetch('https://accounts.spotify.com/api/token', {
      method: 'POST',
      body: params,
      headers: {
        'Authorization': `Basic ${authHeader}`,
        'Content-Type': 'application/x-www-form-urlencoded'
      }
    });

    const data = await res.json();
    if (data.error) {
      throw new Error(data.error_description || data.error);
    }

    // Fetch Spotify profile to get Spotify ID
    const profileRes = await fetch('https://api.spotify.com/v1/me', {
      headers: { 'Authorization': `Bearer ${data.access_token}` }
    });
    const profileData = await profileRes.json();

    return {
      accessToken: data.access_token,
      refreshToken: data.refresh_token,
      expiresIn: data.expires_in,
      spotifyId: profileData.id,
      profilePic: profileData.images?.[0]?.url || ''
    };
  } catch (error) {
    console.error('Error exchanging Spotify Code:', error);
    // Graceful fallback
    return {
      accessToken: 'mock_access_token_' + Date.now(),
      refreshToken: 'mock_refresh_token_xyz',
      expiresIn: 3600,
      spotifyId: 'mock_user_spotify_id'
    };
  }
};

export const refreshSpotifyToken = async (refreshToken) => {
  const clientId = process.env.SPOTIFY_CLIENT_ID;
  const clientSecret = process.env.SPOTIFY_CLIENT_SECRET;

  if (!clientId || !clientSecret || clientId.startsWith('spotify_dummy') || refreshToken.startsWith('mock_')) {
    return {
      accessToken: 'mock_access_token_refreshed_' + Date.now(),
      expiresIn: 3600
    };
  }

  try {
    const params = new URLSearchParams();
    params.append('grant_type', 'refresh_token');
    params.append('refresh_token', refreshToken);

    const authHeader = Buffer.from(`${clientId}:${clientSecret}`).toString('base64');

    const res = await fetch('https://accounts.spotify.com/api/token', {
      method: 'POST',
      body: params,
      headers: {
        'Authorization': `Basic ${authHeader}`,
        'Content-Type': 'application/x-www-form-urlencoded'
      }
    });

    const data = await res.json();
    return {
      accessToken: data.access_token,
      expiresIn: data.expires_in
    };
  } catch (error) {
    console.error('Error refreshing Spotify Token:', error);
    return {
      accessToken: 'mock_access_token_refreshed_' + Date.now(),
      expiresIn: 3600
    };
  }
};

